/** Traduce un nombre que viene de los datos; si no está en la tabla, queda en español. */
export function nom(texto: string, idioma: Idioma): string {
  if (idioma === "es") return texto;
  const par = nombres[texto];
  return par ? par[idioma === "en" ? 0 : 1] : texto;
}
